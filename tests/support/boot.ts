import { getDb, runMigrations } from "@/server/db";
import { FakePayPal } from "@/server/paypal/fake";
import type { CreateOrderInput } from "@/server/paypal/client";
import { MemoryStorageProvider } from "@/server/storage";
import type { VisionExtractInput } from "@/server/agent/vision/provider";
import { renderScoreboardPng } from "@/server/demo/scoreboard";
import { testOverrides } from "@/server/test-overrides";

class CheckoutPayPal extends FakePayPal {
  override async createOrder(input: CreateOrderInput) {
    const order = await super.createOrder(input);
    this.approveOrder(order.orderId);
    const url = new URL(input.returnUrl); url.searchParams.set("token", order.orderId);
    return { ...order, approveUrl: url.toString() };
  }
}
/** Reads only images generated by the test scoreboard renderer; never used by hosted demos. */
class ScoreboardTestVision {
  async extractRaw(input: VisionExtractInput) {
    const [a,b] = input.expectedGamertags;
    const same = (bytes: Uint8Array) => Buffer.from(bytes).equals(Buffer.from(input.imageBytes));
    const blurry = same(renderScoreboardPng({ homeName:a, awayName:b, homeScore:3, awayScore:1, variant:"blurry" }));
    const reversed = same(renderScoreboardPng({ homeName:a, awayName:b, homeScore:1, awayScore:3, variant:"mismatch_b" }));
    return JSON.stringify({ readable: !blurry, game_over: !blurry, home: { name:a, score: blurry ? null : reversed ? 1 : 3 }, away: { name:b, score: blurry ? null : reversed ? 3 : 1 }, confidence: blurry ? 0.1 : 0.99, notes: "Automated test fixture" });
  }
}
export async function bootE2E() {
  testOverrides(); // Validate isolation before constructing providers or migrating.
  if (globalThis.__umpraE2E) return;
  const db = getDb();
  await runMigrations(db);
  globalThis.__umpraE2E = { db, paypal: new CheckoutPayPal(), storage: new MemoryStorageProvider(), vision: new ScoreboardTestVision() };
}
